import assert from 'node:assert/strict';
import { test } from 'node:test';
import { mkdtempSync, mkdirSync, readFileSync, rmSync } from 'node:fs';
import { join, resolve, sep } from 'node:path';
import { tmpdir } from 'node:os';
import { chromium } from 'patchright';
import type { CandidateProfile } from '../types.js';
import type { ToolContext } from './context.js';
import { withApplicationModel } from '../application-model.js';
import { doCompleteAuthentication, doRecordAuthenticationResult } from './authentication.js';
import { storedCredential, commitAcceptedCredentials } from '../site-credentials.js';
import { observe } from './observe.js';

// Native browser fixture only: no employer, real account, mailbox or model call.
test('unknown credentials, rejected logins, accepted recovery and account isolation use actual observed state', async () => {
 const directory=mkdtempSync(join(tmpdir(),'owtomate-auth-state-'));
 const previousSecret=process.env.SITE_AUTH_SECRET;
 process.env.SITE_AUTH_SECRET='fixture-only-authentication-secret';
 const profile={name:'Fixture Candidate',email:'candidate@fixture.invalid',phone:'0400000000'} as CandidateProfile;
 const browser=await chromium.launch({headless:true,...(process.env.CHROME_PATH?{executablePath:process.env.CHROME_PATH}:process.platform==='win32'?{channel:'chrome'}:{})});
 const page=await browser.newPage();
 const pageForm='<main><h1>Candidate account</h1><label>Email<input id=email type=email></label><label>Password<input id=password type=password></label><button id=continue onclick="document.querySelector(\'main\').innerHTML=\'<p>Invalid email address or password. Please re-enter your login info.</p>\'+document.querySelector(\'main\').innerHTML">Sign in</button></main>';
 await page.route('**/*',route=>new URL(route.request().url()).hostname.endsWith('.invalid')?route.fulfill({contentType:'text/html',body:pageForm}):route.abort());
 try { await withApplicationModel({DATA_DIR:directory},async()=>{
  await page.goto('https://employer.fixture.invalid/login');
  const context=async()=>({page,profile,job:{id:'fixture',title:'Fixture',company:'Fixture'},observation:await observe(page),actions:[],captured:[],log:()=>{}} as unknown as ToolContext);
  const inputs={targets:[{selector:'#email'},{selector:'#password'}]};
  let ctx=await context();
  const unknown=await doCompleteAuthentication(ctx,{purpose:'sign_in',...inputs});
  assert.match(unknown.kind==='ok'?unknown.message:'',/No verified usable password/);
  assert.equal(await page.locator('#password').inputValue(),'');
  assert.equal(ctx.actions.length,0);
  await doCompleteAuthentication(ctx,{purpose:'create_account',...inputs});
  const proposed=await page.locator('#password').inputValue();assert.ok(proposed.length>=12);
  assert.equal(storedCredential(page.url(),profile.email),null,'prepared fields cannot persist a password');
  await page.setContent('<main><p>There is already an account with this email address.</p></main>');
  await doRecordAuthenticationResult(ctx,{purpose:'create_account',outcome:'rejected',evidence:'There is already an account with this email address.'});
  assert.equal(ctx.pendingCredentials?.size,0);
  await page.setContent(pageForm);
  await doCompleteAuthentication(ctx,{purpose:'sign_in',...inputs});
  assert.equal(await page.locator('#password').inputValue(),'','a rejected registration never authorizes a sign-in');
  await doCompleteAuthentication(ctx,{purpose:'create_account',...inputs});
  const acceptedPassword=await page.locator('#password').inputValue();
  await page.setContent('<main><p>Your candidate account has been created successfully.</p></main>');
  await doRecordAuthenticationResult(ctx,{purpose:'create_account',outcome:'accepted',evidence:'Your candidate account has been created successfully.'});
  assert.ok(storedCredential(page.url(),profile.email));
  assert.equal(ctx.pendingCredentials?.size,0);
  await page.setContent(pageForm);
  await doCompleteAuthentication(ctx,{purpose:'create_account',password_rules:{max_length:14},...inputs});
  assert.ok(ctx.pendingCredentials?.size);
  await page.setContent(pageForm);
  await doCompleteAuthentication(ctx,{purpose:'sign_in',...inputs});
  assert.equal(await page.locator('#password').inputValue(),acceptedPassword,'an unaccepted proposal cannot displace the actual saved login');
  assert.equal(ctx.pendingCredentials?.size,0);
  await page.setContent('<main><p>Your candidate profile is now available.</p></main>');
  await doRecordAuthenticationResult(ctx,{purpose:'sign_in',outcome:'accepted',evidence:'Your candidate profile is now available.'});
  assert.equal(storedCredential(page.url(),profile.email)?.rules?.max_length,undefined,'sign-in acceptance cannot commit a password that was not used');
  await page.setContent(pageForm);ctx=await context();
  const login=await doCompleteAuthentication(ctx,{purpose:'sign_in',...inputs});
  assert.equal(await page.locator('#password').inputValue(),acceptedPassword);
  assert.ok(!JSON.stringify(login).includes(acceptedPassword),'private values must never enter tool messages');
  await page.locator('#continue').click();
  const message='Invalid email address or password. Please re-enter your login info.';
  const misreported=await doRecordAuthenticationResult(ctx,{purpose:'sign_in',outcome:'accepted',evidence:message});
  assert.match(misreported.kind==='ok'?misreported.message:'',/editable password form/);
  assert.ok(!ctx.actions.some(a=>a.kind==='signed-in'),'a rejected login cannot be recorded as accepted');
  await doRecordAuthenticationResult(ctx,{purpose:'sign_in',outcome:'rejected',evidence:message});
  assert.equal(await page.locator('#password').inputValue(),'','the rejected private value is retired from the live form too');
  assert.equal(storedCredential(page.url(),profile.email),null);
  const rejected=JSON.parse(readFileSync(resolve(directory,'site-credentials.json'),'utf8'));
  assert.equal(Object.values(rejected).length,1);
  assert.ok(!JSON.stringify(rejected).includes(acceptedPassword),'persistence stores metadata, never a password');
  await page.setContent(pageForm);ctx=await context();
  await doCompleteAuthentication(ctx,{purpose:'sign_in',...inputs});
  assert.equal(await page.locator('#password').inputValue(),'','rejection survives a fresh application context');
  await page.setContent('<main><p>If an account exists, a recovery email will be sent.</p></main>');
  await doRecordAuthenticationResult(ctx,{purpose:'reset_password',outcome:'needs_verification',evidence:'If an account exists, a recovery email will be sent.'});
  assert.equal(storedCredential(page.url(),profile.email),null,'a requested email is not an accepted password reset');
  await page.setContent(pageForm);
  await doCompleteAuthentication(ctx,{purpose:'reset_password',password_rules:{max_length:16},...inputs});
  const resetPassword=await page.locator('#password').inputValue();assert.ok(resetPassword);
  await page.setContent('<main><p>Your password has been reset successfully.</p></main>');
  await doRecordAuthenticationResult(ctx,{purpose:'reset_password',outcome:'accepted',evidence:'Your password has been reset successfully.'});
  assert.ok(storedCredential(page.url(),profile.email),'confirmed recovery releases the rejected credential state');
  await page.setContent(pageForm);ctx=await context();
  await doCompleteAuthentication(ctx,{purpose:'sign_in',...inputs});
  assert.equal(await page.locator('#password').inputValue(),resetPassword);
  assert.equal(storedCredential(page.url(),'different@fixture.invalid'),null);
  assert.equal(storedCredential('https://another.fixture.invalid',profile.email),null);
  const foreign=join(directory,'other-owner');mkdirSync(foreign);
  await withApplicationModel({DATA_DIR:foreign},async()=>assert.equal(storedCredential(page.url(),profile.email),null));
  await page.setContent('<main><p>Your password has been reset successfully.</p></main>');
  const before=ctx.actions.length;
  const missing=await doRecordAuthenticationResult(ctx,{purpose:'sign_in',evidence:'Your password has been reset successfully.'});
  assert.equal(missing.kind==='ok'?missing.disposition:'','invalid-arguments');
  await doRecordAuthenticationResult(ctx,{purpose:'sign_in',outcome:'accepted',evidence:'A fabricated successful sign-in message.'});
  assert.equal(ctx.actions.length,before,'missing outcomes and fabricated page evidence cannot write success');
  const proposalMap=new Map([['employer.fixture.invalid',{format:'readable-v1' as const,rules:{max_length:24}}]]);
  commitAcceptedCredentials(proposalMap,[{kind:'password-reset',site:'employer.fixture.invalid',email:'another@fixture.invalid',at:new Date().toISOString(),detail:'Foreign event'}],profile.email);
  assert.equal(proposalMap.size,1,'another email cannot accept this account credential');
 });}finally{await browser.close();if(previousSecret===undefined)delete process.env.SITE_AUTH_SECRET;else process.env.SITE_AUTH_SECRET=previousSecret;const target=resolve(directory);assert.ok(target.startsWith(resolve(tmpdir())+sep));rmSync(target,{recursive:true,force:true});}
});
